def t(key: str, lang: str = "ja") -> str:
    """Return the translated string for *key* in the given language.

    Falls back to Japanese if the language is not found,
    and returns the key itself if the key is missing.
    """
    return LANG.get(lang, LANG["ja"]).get(key, key)
